static arm_fir_instance_f32 s_ecg_fir;

// 状态数组长度必须是 numTaps + blockSize − 1 = 129 + 1 − 1 = 129。
// 写小了会越界读（不报错，但会读到别的变量，波形莫名跳动），
// 写大了只是浪费 RAM。这一份是 129，正确。
static float32_t s_ecg_state[ECG_FIR_TAP_NUM + ECG_FIR_BLOCK_SIZE - 1];

//带通滤波初始化
void ECG_Filter_Init(void)
{
    // 第三个实参本应是 const，CMSIS 形参不带 const，这里的强转只是迁就 API；系数在 Flash 中不会被改
    arm_fir_init_f32(&s_ecg_fir, ECG_FIR_TAP_NUM,
                     (float32_t *)s_ecg_bandpass_coeffs, s_ecg_state,
                     ECG_FIR_BLOCK_SIZE);
}

/**
 * @brief  逐点滤波。
 * @param  input  已归一化的采样值（±1 对应满量程；由 pan_tompkins.c 归一化）
 * @return 带通后的信号（通带增益≈1，所以量纲不变）
 * @note   前 64 个点输出的是"状态缓冲还没填满"的过渡结果，偏小但不发散。
 *         因为 pan_tompkins 有 2 秒学习期，正好把这段糊掉。
 */
float32_t ECG_Filter_Process(float32_t input)
{
    float32_t output;
    arm_fir_f32(&s_ecg_fir, &input, &output, ECG_FIR_BLOCK_SIZE);
    return output;
}
